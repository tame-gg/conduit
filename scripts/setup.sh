#!/usr/bin/env bash
# setup.sh — Clones upstream Velocity-CTD, applies Conduit overlays, and prepares the build tree.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

UPSTREAM_REPO="https://github.com/GemstoneGG/Velocity-CTD.git"
# Pinned to an exact Velocity-CTD commit on dev/4.0.0 (the old libdeflate branch was deleted).
UPSTREAM_BRANCH="dev/4.0.0"
UPSTREAM_COMMIT="2c8f0504b74c8218a7d31bcd1f8c9e6ce4288f5e"
UPSTREAM_DIR="$ROOT_DIR/.upstream-velocity"
CI_MODE=false

for arg in "$@"; do
  [[ "$arg" == "--ci" ]] && CI_MODE=true
done

echo "==> Conduit setup"
echo "    Root:     $ROOT_DIR"
echo "    Upstream: $UPSTREAM_REPO @ $UPSTREAM_BRANCH ($UPSTREAM_COMMIT)"
echo ""

# ── 1. Clone or update upstream ──────────────────────────────────────────────
if [[ ! -d "$UPSTREAM_DIR/.git" ]]; then
  echo "==> Initialising upstream Velocity-CTD clone..."
  git init -q "$UPSTREAM_DIR"
  git -C "$UPSTREAM_DIR" remote add origin "$UPSTREAM_REPO"
fi
echo "==> Fetching pinned upstream commit $UPSTREAM_COMMIT (depth=1)..."
git -C "$UPSTREAM_DIR" remote set-url origin "$UPSTREAM_REPO"
git -C "$UPSTREAM_DIR" fetch --depth=1 origin "$UPSTREAM_COMMIT"
git -C "$UPSTREAM_DIR" checkout -q --detach FETCH_HEAD
ACTUAL="$(git -C "$UPSTREAM_DIR" rev-parse HEAD)"
if [[ "$ACTUAL" != "$UPSTREAM_COMMIT" ]]; then
  echo "::error::upstream HEAD is $ACTUAL, expected $UPSTREAM_COMMIT" >&2
  exit 1
fi

# ── 2. Copy upstream source into our project tree ────────────────────────────
echo "==> Syncing upstream source files..."

for module in api native proxy bootstrap permission-integration build-logic config; do
  if [[ -d "$UPSTREAM_DIR/$module" ]]; then
    rsync -a --delete \
      --exclude='**/KnownPacksPacket.java' \
      --exclude='**/ConnectionManager.java' \
      --exclude='**/VelocityServer.java' \
      --exclude='**/ServerChannelInitializer.java' \
      --exclude='**/HandshakeSessionHandler.java' \
      "$UPSTREAM_DIR/$module/" "$ROOT_DIR/$module/"
  fi
done

# Copy upstream-owned Gradle support files into the generated working tree.
for f in gradlew gradlew.bat gradle HEADER.txt HEADER-CTD.txt; do
  if [[ -e "$UPSTREAM_DIR/$f" ]]; then
    rm -rf "$ROOT_DIR/$f"
    cp -r "$UPSTREAM_DIR/$f" "$ROOT_DIR/$f"
  fi
done
chmod +x "$ROOT_DIR/gradlew" 2>/dev/null || true

# ── 3. Apply Conduit overlays (modified upstream files) ─────────────────
echo "==> Applying overlays (modified upstream files)..."
if [[ -d "$ROOT_DIR/overlays" ]]; then
  rsync -a "$ROOT_DIR/overlays/" "$ROOT_DIR/"
  echo "    Overlays applied."
fi

# ── 4. Apply Conduit additions (new files) ─────────────────────────────
echo "==> Applying additions (new Conduit files)..."
if [[ -d "$ROOT_DIR/additions" ]]; then
  rsync -a "$ROOT_DIR/additions/" "$ROOT_DIR/"
  echo "    Additions applied."
fi

# ── 5. Conduit build metadata ────────────────────────────────────────────────
# conduit-build.properties (version, build time, git hash) is now generated by the Gradle build
# (see the generateConduitBuildProperties task in the proxy build script) so it always matches
# conduit.version. Remove any stale copy an older setup script may have written into the source tree
# so the build-time copy is the single source of truth.
rm -f "$ROOT_DIR/proxy/src/main/resources/com/velocitypowered/proxy/conduit/conduit-build.properties"

echo "==> Setup complete. Run './gradlew build' to compile."
